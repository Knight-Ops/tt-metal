"""End-to-end benchmark on the REAL Qwen3.6-35B-A3B model with real prompts (not the toy one).

Builds the full model once (QWEN36_LAYERS, default 40), then for each of a set of realistic prompts of
varying length runs the production path — chat-templated prefill (TTFT + prefill tok/s) followed by
traced single-user greedy decode (tok/s/user) — and generates real text. Emits a Markdown report
(config + results table + how-to-reproduce) to stdout, and to --md-out if given, so CURRENT_BENCHMARK.md
is regenerated by re-running this script.

Run (tt-metal python_env; full model):
    QWEN36_LAYERS=40 ./python_env/bin/python models/demos/qwen3_6_a3b/tests/benchmark.py \
        --gen 32 --md-out models/demos/qwen3_6_a3b/CURRENT_BENCHMARK.md

Per-component (MoE/attention/gated-delta) device-time breakdowns are a separate concern — use the
signpost profiler (QWEN36_SIGNPOST=1 + tests/signpost_report.py; see DEBUGGING.md §1.5.1) or
tests/bench_decode.py::bench_components.
"""
from __future__ import annotations

import argparse
import json
import os
import time

import torch

import ttnn
from models.demos.qwen3_6_a3b.tests import bench_decode as bd
from models.demos.qwen3_6_a3b.tt.load_checkpoints import CheckpointLoader
from models.demos.qwen3_6_a3b.tt.model import TtModel
from models.demos.qwen3_6_a3b.tt.model_config import ModelArgs

# Realistic prompts of increasing length (short QA → instruction → code → reasoning → RAG-style
# long context). Each is sent through the tokenizer's chat template when available, so the measured
# prefill lengths and generated text match real single-user serving. Override with --prompts-file
# (a JSON list of {"label","text"} objects, or one prompt per line).
_LONG_CONTEXT = (
    "The Tenstorrent Blackhole is a RISC-V-based AI accelerator built around a grid of Tensix cores, "
    "each pairing five baby-RISC-V processors with a matrix engine and local SRAM. Unlike GPUs, the "
    "architecture exposes an explicit software-managed memory hierarchy and a network-on-chip that the "
    "compiler schedules directly, so data movement between cores and DRAM is programmed rather than "
    "cached implicitly. Kernels are compiled just-in-time for each operation, and models are expressed "
    "as graphs of these operations in the TT-NN library. A key performance technique is tracing: the "
    "sequence of on-device commands for one decode step is captured once and replayed, which removes the "
    "host dispatch overhead that otherwise dominates the many small operations of autoregressive "
    "generation. Mixture-of-experts models add a routing step that selects a small subset of expert "
    "feed-forward networks per token, so most of the model's parameters stay idle on any given step."
)
REAL_PROMPTS = [
    ("short_qa", "What is the capital of France, and what river runs through it?"),
    ("instruction", "Write a short haiku about autumn leaves falling in a quiet garden."),
    ("code", "Write a Python function that returns the nth Fibonacci number using memoization, with a docstring."),
    (
        "reasoning",
        "A train travels 60 miles per hour for 2 hours and 30 minutes, then 45 miles per hour for 1 hour. "
        "How far does it travel in total? Show your reasoning step by step.",
    ),
    (
        "long_context",
        f"{_LONG_CONTEXT}\n\nUsing only the passage above, explain in two or three sentences why tracing "
        "matters for decode performance on this architecture.",
    ),
]


def _load_prompts(path):
    if not path:
        return REAL_PROMPTS
    with open(path) as f:
        text = f.read()
    try:
        data = json.loads(text)
        return [(d.get("label", f"prompt_{i}"), d["text"]) for i, d in enumerate(data)]
    except json.JSONDecodeError:
        return [(f"prompt_{i}", line) for i, line in enumerate(l for l in text.splitlines() if l.strip())]


def _get_tokenizer(ckpt):
    from transformers import AutoTokenizer  # hard dependency: real prompts need the real tokenizer

    return AutoTokenizer.from_pretrained(ckpt)


def _encode(tok, text):
    """Chat-template the prompt when the tokenizer provides one (the real serving path); else raw."""
    if getattr(tok, "chat_template", None):
        out = tok.apply_chat_template(
            [{"role": "user", "content": text}], add_generation_prompt=True, return_tensors="pt"
        )
        # transformers >= 5.11 returns a BatchEncoding here instead of a bare Tensor; normalize the
        # same way demo/runner.py and demo/server.py do.
        ids = out["input_ids"] if not isinstance(out, torch.Tensor) else out
        return ids.to(torch.long)
    return torch.tensor([tok.encode(text)], dtype=torch.long)


def _dtype_name(dt):
    return str(dt).rsplit(".", 1)[-1]  # ttnn.DataType.BFLOAT4_B -> BFLOAT4_B


def _best_prefill_ms(model, ids, iters):
    """Warm once (compile for this length), then best-of-`iters` wall-clock prefill time (ms)."""
    model.forward(ids)  # warmup (compile); not timed
    best = float("inf")
    for _ in range(max(1, iters)):
        t0 = time.time()
        logits = model.forward(ids)
        best = min(best, time.time() - t0)
    return best * 1e3, logits


def _decode_traced(model, first_token, gen, drop=2):
    """Capture the decode trace for this prompt's state and generate `gen` greedy tokens with the
    traced path (the demo tok/s/user metric). Returns (tokens, ms_per_token) timed over the steady
    state (first `drop` steps dropped as warmup)."""
    model.start_decode(first_token)
    model.decode_step_eager()  # warmup: compile decode kernels (safe to call repeatedly)
    model.capture_decode_trace()
    for _ in range(3):  # warm replays
        model.decode_step_traced()
    tokens, times = [first_token], []
    nxt = first_token
    for step in range(gen):
        t0 = time.time()
        nxt = model.decode_step_traced()
        times.append(time.time() - t0)
        tokens.append(nxt)
    steady = times[drop:] or times
    return tokens, sum(steady) / len(steady) * 1e3


def run(mesh, n_layers, ckpt, max_seq, prompts, gen, prefill_iters):
    args = ModelArgs(mesh, ckpt_dir=ckpt, max_seq_len=max_seq)
    tok = _get_tokenizer(ckpt)
    t0 = time.time()
    model = TtModel(mesh, args, CheckpointLoader(ckpt), num_layers=n_layers)
    load_s = time.time() - t0
    print(f"[bench] built {n_layers}-layer model in {load_s:.0f}s; running {len(prompts)} prompts, gen={gen}\n")

    rows = []
    for label, text in prompts:
        ids = _encode(tok, text)
        T = ids.shape[1]
        if T + gen > max_seq:
            print(f"[bench] skip '{label}': {T}+{gen} tokens exceeds max_seq {max_seq}")
            continue
        prefill_ms, logits = _best_prefill_ms(model, ids, prefill_iters)
        first = int(logits[0, -1].argmax())
        tokens, dec_ms = _decode_traced(model, first, gen)
        out_text = tok.decode(tokens[1:], skip_special_tokens=True).strip().replace("\n", " ")
        rows.append(
            {
                "label": label,
                "prompt_tokens": T,
                "ttft_ms": prefill_ms,
                "prefill_tps": T / (prefill_ms / 1e3),
                "decode_tps": 1e3 / dec_ms,
                "decode_ms": dec_ms,
                "gen": gen,
                "text": out_text,
            }
        )
        print(
            f"  {label:14s} T={T:5d}  TTFT {prefill_ms:8.1f} ms  prefill {rows[-1]['prefill_tps']:7.1f} tok/s"
            f"  decode {rows[-1]['decode_tps']:6.2f} tok/s/user"
        )
    return args, model, rows, load_s


def traced_breakdown(mesh, model, args, iters):
    """Real per-component decode times (wall-clock traced replays, NO profiler → un-inflated and
    stable at 40 layers). Reuses bench_decode: the full-model traced step + each component in its own
    trace × per-token layer counts. This is the ground-truth 'kernel time in the traced step'."""
    dev_ms, full_ms = bd.bench_full_model(mesh, model, iters)
    c = bd.bench_components(mesh, model, args, iters)
    counts = {"gated-delta": bd.N_GATED_DELTA, "attention": bd.N_ATTENTION, "moe": bd.N_MOE, "lm_head": bd.N_HEAD}
    est = sum(c.get(k, 0) * n for k, n in counts.items())
    print(
        f"\n  [traced breakdown] full-model {full_ms:.2f} ms/tok ({1e3/full_ms:.1f} tok/s/user); "
        f"component-sum {est:.2f} ms"
    )
    return {
        "full_model_dev_ms": dev_ms,
        "full_model_ms": full_ms,
        "full_model_tok_s": 1e3 / full_ms,
        "component_ms": {k: c.get(k, 0.0) for k in counts},
        "component_totals_ms": {k: c.get(k, 0.0) * counts[k] for k in counts},
        "layer_counts": counts,
        "moe_router_ms": c.get("moe.router", 0.0),
        "moe_sparse_ms": c.get("moe.sparse", 0.0),
        "sum_ms": est,
        "iters": iters,
    }


# --------------------------------------------------------------------------- markdown report
def breakdown_md(breakdown):
    """Markdown table for the real (un-inflated, traced) per-component decode breakdown."""
    if not breakdown:
        return ""
    b = breakdown
    step = b["full_model_ms"]
    L = [
        f"_Real traced replays (wall-clock, no profiler), {b['iters']} iters. Full traced step: "
        f"**{step:.2f} ms/token** → **{b['full_model_tok_s']:.1f} tok/s/user** "
        f"({b['full_model_dev_ms']:.2f} ms pure `execute_trace`)._\n",
        "| Component | ms/op | × layers | total ms | % of step |",
        "|---|--:|--:|--:|--:|",
    ]
    order = [("gated-delta", "Gated-DeltaNet"), ("attention", "Attention"), ("moe", "MoE"), ("lm_head", "lm_head")]
    for key, name in order:
        ms = b["component_ms"].get(key, 0.0)
        cnt = b["layer_counts"][key]
        tot = b["component_totals_ms"].get(key, 0.0)
        L.append(f"| {name} | {ms:.3f} | {cnt} | {tot:.2f} | {100*tot/step:.1f} |")
    L.append(f"| **sum** | — | — | **{b['sum_ms']:.2f}** | **{100*b['sum_ms']/step:.1f}** |")
    L.append(
        f"\n_MoE split (per op): router+shared `{b['moe_router_ms']:.3f}` ms, "
        f"sparse experts `{b['moe_sparse_ms']:.3f}` ms._\n"
    )
    return "\n".join(L)


def _render_md(args, n_layers, max_seq, rows, gen, prefill_iters, breakdown=None):
    n = len(rows) or 1
    mean_ttft = sum(r["ttft_ms"] for r in rows) / n
    mean_pref = sum(r["prefill_tps"] for r in rows) / n
    mean_dec = sum(r["decode_tps"] for r in rows) / n
    date = time.strftime("%Y-%m-%d %H:%M %Z")
    L = []
    L.append("# Qwen3.6-35B-A3B — Current Benchmark\n")
    L.append(f"_Generated by `models/demos/qwen3_6_a3b/tests/benchmark.py` on {date}._\n")
    L.append(
        "Single-user, single Blackhole. Prefill is chat-templated and greedy; decode is the traced "
        "on-device fast path (the `demo.py --trace` metric). Numbers are wall-clock, no profiler attached.\n"
    )
    L.append("## Configuration\n")
    L.append(
        f"- **Model**: {args.model_name}, **{n_layers} layers** (30 gated-delta + 10 full-attention), "
        f"{args.num_experts} experts / top-{args.num_experts_per_tok} MoE"
    )
    L.append(
        f"- **Weights**: experts `{_dtype_name(args.expert_weight_dtype)}` "
        f"(down `{_dtype_name(args.expert_down_weight_dtype)}`), attention/linear `{_dtype_name(args.attn_weight_dtype)}`, "
        f"activations `{_dtype_name(args.activation_dtype)}`"
    )
    L.append(
        f"- **max_seq_len**: {max_seq}   •   **generated tokens/prompt**: {gen}   •   "
        f"**prefill timing**: best of {prefill_iters}"
    )
    L.append(f"- **Decode**: greedy, traced (`execute_trace` + 1-token readback)\n")
    L.append("## Results\n")
    L.append("| Prompt | Prompt tokens | TTFT (ms) | Prefill (tok/s) | Decode (tok/s/user) |")
    L.append("|---|--:|--:|--:|--:|")
    for r in rows:
        L.append(
            f"| {r['label']} | {r['prompt_tokens']} | {r['ttft_ms']:.1f} | "
            f"{r['prefill_tps']:.1f} | {r['decode_tps']:.2f} |"
        )
    L.append(f"| **mean** | — | **{mean_ttft:.1f}** | **{mean_pref:.1f}** | **{mean_dec:.2f}** |\n")
    if breakdown:
        L.append("## Traced decode — per-component breakdown (real, un-inflated)\n")
        L.append(
            "Where the traced decode step's time goes, by major component. Times are real "
            "`execute_trace` wall-clock (no profiler), so they are the actual traced kernel+gap "
            "times — not inferred from the eager run.\n"
        )
        L.append(breakdown_md(breakdown))
    L.append("### Sample generations (greedy)\n")
    for r in rows:
        snippet = r["text"][:200] + ("…" if len(r["text"]) > 200 else "")
        L.append(f"- **{r['label']}**: {snippet}")
    L.append("")
    L.append("## How to reproduce\n")
    L.append("```bash")
    L.append("# Full 40-layer model, 32 generated tokens/prompt, regenerate this file:")
    L.append("QWEN36_LAYERS=40 ./python_env/bin/python models/demos/qwen3_6_a3b/tests/benchmark.py \\")
    L.append(f"    --gen {gen} --prefill-iters {prefill_iters} \\")
    L.append("    --md-out models/demos/qwen3_6_a3b/CURRENT_BENCHMARK.md")
    L.append("```\n")
    L.append(
        "**Env vars**: `QWEN36_LAYERS` (model depth, 40 = full), `QWEN36_CKPT` (checkpoint dir, "
        "default `~/models/qwen36`), `QWEN36_MAX_SEQ` (KV/activation budget), plus the accuracy/perf "
        "knobs in `tt/model_config.py` (e.g. `QWEN36_EXPERT_DOWN_BF8`). `--prompts-file` takes a JSON "
        'list of `{"label","text"}` or one prompt per line to swap the prompt set.\n'
    )
    L.append("**Notes**\n")
    L.append(
        "- First run after a checkpoint change pays a one-time weight-quantize/cache cost; warm runs "
        "load from the on-disk `.tensorbin` cache. Model-load time is excluded from all figures."
    )
    L.append(
        "- TTFT/prefill-tok/s scale with prompt length (longer prompts amortize fixed overhead → "
        "higher tok/s); decode tok/s/user is largely prompt-independent for a single user."
    )
    L.append(
        "- For per-component (MoE / attention / gated-delta / lm_head) device-time breakdowns, run the "
        "signpost profiler (`QWEN36_SIGNPOST=1` + `tests/signpost_report.py`, see `DEBUGGING.md` §1.5.1) "
        "or `tests/bench_decode.py`."
    )
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--gen", type=int, default=32, help="tokens to generate per prompt")
    ap.add_argument("--prefill-iters", type=int, default=3, help="best-of-N prefill timing")
    ap.add_argument("--prompts-file", type=str, default=None, help="JSON list of {label,text} or one prompt/line")
    ap.add_argument("--md-out", type=str, default=None, help="write the Markdown report to this file too")
    ap.add_argument("--json-out", type=str, default=None, help="write machine-readable JSON here")
    ap.add_argument("--breakdown-iters", type=int, default=100, help="traced-replay iters for the component breakdown")
    ap.add_argument("--no-breakdown", action="store_true", help="skip the traced per-component breakdown")
    a = ap.parse_args()

    ckpt = os.environ.get("QWEN36_CKPT", os.path.expanduser("~/models/qwen36"))
    n_layers = int(os.environ.get("QWEN36_LAYERS", "40"))
    max_seq = int(os.environ.get("QWEN36_MAX_SEQ", "2048"))
    prompts = _load_prompts(a.prompts_file)

    mesh = ttnn.open_mesh_device(ttnn.MeshShape(1, 1), trace_region_size=200 * 1024 * 1024)
    try:
        args, model, rows, _ = run(mesh, n_layers, ckpt, max_seq, prompts, a.gen, a.prefill_iters)
        breakdown = None if a.no_breakdown else traced_breakdown(mesh, model, args, a.breakdown_iters)
    finally:
        ttnn.close_mesh_device(mesh)

    if not rows:
        raise SystemExit("no prompts benchmarked (all skipped?)")
    if a.json_out:
        config = {
            "model_name": args.model_name,
            "n_layers": n_layers,
            "num_experts": args.num_experts,
            "num_experts_per_tok": args.num_experts_per_tok,
            "max_seq": max_seq,
            "gen": a.gen,
            "prefill_iters": a.prefill_iters,
            "expert_dtype": _dtype_name(args.expert_weight_dtype),
            "expert_down_dtype": _dtype_name(args.expert_down_weight_dtype),
            "attn_dtype": _dtype_name(args.attn_weight_dtype),
            "activation_dtype": _dtype_name(args.activation_dtype),
        }
        with open(a.json_out, "w") as f:
            json.dump({"config": config, "rows": rows, "breakdown": breakdown}, f, indent=2)
        print(f"[bench] wrote {a.json_out}")
    md = _render_md(args, n_layers, max_seq, rows, a.gen, a.prefill_iters, breakdown)
    print("\n" + "=" * 70 + "\n" + md)
    if a.md_out:
        with open(a.md_out, "w") as f:
            f.write(md)
        print(f"[bench] wrote {a.md_out}")


if __name__ == "__main__":
    main()
